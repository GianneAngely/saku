import AppKit
import Observation
import SwiftUI

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, link, image, files }

    var id = UUID()
    var kind: Kind
    var text = ""                   // plain text (text, link) or a description (image, files)
    var rtfFile: String?            // rich text kept next to the plain text, in Saku's Clipboard folder
    var imageFile: String?          // PNG in Saku's Clipboard folder
    var paths: [String] = []        // files
    var app = ""                    // name of the app that was in front when it was copied
    var appID = ""
    var date = Date()
    var pinned = false
    var width = 0, height = 0       // image size in pixels

    var title: String {
        switch kind {
        case .text, .link: text.trimmingCharacters(in: .whitespacesAndNewlines).split(separator: "\n").first.map(String.init) ?? text
        case .image: tr("Image %d × %d", width, height)
        case .files: paths.count == 1 ? (paths[0] as NSString).lastPathComponent : tr("%d files", paths.count)
        }
    }

    var icon: String {
        switch kind {
        case .text: rtfFile == nil ? "text.alignleft" : "textformat"
        case .link: "link"
        case .image: "photo"
        case .files: "doc.on.doc"
        }
    }
}

struct Snippet: Codable, Identifiable, Equatable {
    var id = UUID()
    var title: String
    var text: String
    var collection = ""
}

struct ClipboardSave: Codable {
    var history: [ClipItem] = []
    var snippets: [Snippet] = []
    var collections: [String] = []
}

@MainActor @Observable
final class ClipboardModel {
    private(set) var history: [ClipItem] = []
    private(set) var snippets: [Snippet] = []
    private(set) var collections: [String] = []
    /// Which side of the Clipboard tab is showing: 0 history, 1 snippets.
    var mode = 0

    @ObservationIgnored let pasteboard: NSPasteboard
    @ObservationIgnored private let prefs: Prefs
    @ObservationIgnored private let store = JSONStore<ClipboardSave>("clipboard.json")
    @ObservationIgnored let folder: URL
    @ObservationIgnored private var lastChange: Int
    @ObservationIgnored private var poll: Timer?
    @ObservationIgnored private let saver = Debouncer(0.6)
    /// Change count right after Saku itself wrote to the pasteboard (so it is not recorded twice).
    @ObservationIgnored private var ownChange = -1

    static let concealed: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init(prefs: Prefs, pasteboard: NSPasteboard = .general, watch: Bool = true) {
        self.prefs = prefs
        self.pasteboard = pasteboard
        folder = Paths.folder("Clipboard")
        lastChange = pasteboard.changeCount
        if let s = store.load() {
            history = s.history
            snippets = s.snippets
            collections = s.collections
        }
        if watch { start() }
    }

    func start() {
        poll?.invalidate()
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common)
        poll = t
    }

    func stop() {
        poll?.invalidate()
        poll = nil
    }

    func tick() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard prefs.v.clipboardEnabled, !prefs.v.clipboardPaused, lastChange != ownChange else { return }
        let front = NSWorkspace.shared.frontmostApplication
        capture(from: pasteboard, app: front?.localizedName ?? "", appID: front?.bundleIdentifier ?? "")
    }

    // MARK: Capture

    /// Reads the top item of a pasteboard into history. Secrets and ignored apps are skipped.
    @discardableResult
    func capture(from pb: NSPasteboard, app: String = "", appID: String = "") -> ClipItem? {
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.concealed), !prefs.v.clipboardIgnoreApps.contains(appID) else { return nil }
        var item: ClipItem?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(kind: .files, text: urls.map(\.path).joined(separator: "\n"), paths: urls.map(\.path))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = URL(string: trimmed).flatMap(\.scheme).map { ["http", "https", "mailto", "ftp"].contains($0) } ?? false
                && !trimmed.contains(where: \.isWhitespace)
            var c = ClipItem(kind: isLink ? .link : .text, text: String(s.prefix(1_000_000)))
            if !isLink, let rtf = pb.data(forType: .rtf), rtf.count < 2_000_000 {
                c.rtfFile = write(rtf, ext: "rtf")
            }
            item = c
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count < 40_000_000,
                  let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) {
            item = ClipItem(kind: .image, imageFile: write(png, ext: "png"), width: rep.pixelsWide, height: rep.pixelsHigh)
        }
        guard var new = item else { return nil }
        new.app = app
        new.appID = appID
        // Same content again: move the old entry to the top instead of duplicating it.
        if let old = history.firstIndex(where: { same($0, new) }) {
            var moved = history.remove(at: old)
            moved.date = Date()
            discardFiles(of: new)
            history.insert(moved, at: 0)
            changed()
            return moved
        }
        history.insert(new, at: 0)
        trim()
        changed()
        return new
    }

    private func same(_ a: ClipItem, _ b: ClipItem) -> Bool {
        guard a.kind == b.kind else { return false }
        switch a.kind {
        case .text, .link: return a.text == b.text
        case .files: return a.paths == b.paths
        case .image:
            guard let fa = a.imageFile, let fb = b.imageFile else { return false }
            return FileManager.default.contentsEqual(atPath: folder.appendingPathComponent(fa).path, andPath: folder.appendingPathComponent(fb).path)
        }
    }

    private func write(_ data: Data, ext: String) -> String? {
        let name = UUID().uuidString + "." + ext
        do {
            try data.write(to: folder.appendingPathComponent(name))
            return name
        } catch {
            return nil
        }
    }

    private func discardFiles(of item: ClipItem) {
        for f in [item.rtfFile, item.imageFile].compactMap({ $0 }) { try? FileManager.default.removeItem(at: folder.appendingPathComponent(f)) }
    }

    private func trim() {
        let limit = max(10, prefs.v.clipboardLimit)
        var unpinned = history.filter { !$0.pinned }
        while unpinned.count > limit, let last = unpinned.popLast() {
            history.removeAll { $0.id == last.id }
            discardFiles(of: last)
        }
    }

    private func changed() { saver.run { [weak self] in self?.saveNow() } }

    func saveNow() { store.save(ClipboardSave(history: history, snippets: snippets, collections: collections)) }

    // MARK: Using items

    func image(of item: ClipItem) -> NSImage? {
        item.imageFile.flatMap { NSImage(contentsOf: folder.appendingPathComponent($0)) }
    }

    func rtf(of item: ClipItem) -> Data? {
        item.rtfFile.flatMap { try? Data(contentsOf: folder.appendingPathComponent($0)) }
    }

    /// Puts an item back on the clipboard (rich text too, unless `plain`).
    func copy(_ item: ClipItem, plain: Bool = false) {
        let pb = pasteboard
        pb.clearContents()
        switch item.kind {
        case .text, .link:
            if !plain, let rtf = rtf(of: item) { pb.setData(rtf, forType: .rtf) }
            pb.setString(item.text, forType: .string)
        case .image:
            if let f = item.imageFile, let data = try? Data(contentsOf: folder.appendingPathComponent(f)) { pb.setData(data, forType: .png) }
        case .files:
            pb.writeObjects(item.paths.map { URL(fileURLWithPath: $0) as NSURL })
        }
        ownChange = pb.changeCount
        lastChange = pb.changeCount
        if let i = history.firstIndex(where: { $0.id == item.id }) {   // used again: back to the top
            var moved = history.remove(at: i)
            moved.date = Date()
            history.insert(moved, at: 0)
            changed()
        }
    }

    func copy(text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        ownChange = pasteboard.changeCount
        lastChange = pasteboard.changeCount
    }

    func togglePin(_ item: ClipItem) {
        guard let i = history.firstIndex(where: { $0.id == item.id }) else { return }
        history[i].pinned.toggle()
        changed()
    }

    func delete(_ item: ClipItem) {
        history.removeAll { $0.id == item.id }
        discardFiles(of: item)
        changed()
    }

    /// Clears history but keeps pinned items.
    func clearHistory() {
        for i in history where !i.pinned { discardFiles(of: i) }
        history.removeAll { !$0.pinned }
        changed()
    }

    func search(_ q: String) -> [ClipItem] {
        let pinnedFirst = history.filter(\.pinned) + history.filter { !$0.pinned }
        let query = q.trimmingCharacters(in: .whitespaces)
        guard !query.isEmpty else { return pinnedFirst }
        return pinnedFirst.filter { $0.text.localizedCaseInsensitiveContains(query) || $0.app.localizedCaseInsensitiveContains(query) }
    }

    // MARK: Snippets

    func addSnippet(title: String, text: String, collection: String = "") -> Snippet {
        let s = Snippet(title: title.isEmpty ? String(text.prefix(40)) : title, text: text, collection: collection)
        snippets.insert(s, at: 0)
        if !collection.isEmpty && !collections.contains(collection) { collections.append(collection) }
        changed()
        return s
    }

    func updateSnippet(_ s: Snippet) {
        guard let i = snippets.firstIndex(where: { $0.id == s.id }) else { return }
        snippets[i] = s
        if !s.collection.isEmpty && !collections.contains(s.collection) { collections.append(s.collection) }
        changed()
    }

    func deleteSnippet(_ s: Snippet) {
        snippets.removeAll { $0.id == s.id }
        changed()
    }

    func addCollection(_ name: String) {
        let n = name.trimmingCharacters(in: .whitespaces)
        guard !n.isEmpty, !collections.contains(n) else { return }
        collections.append(n)
        changed()
    }

    func deleteCollection(_ name: String) {
        collections.removeAll { $0 == name }
        for i in snippets.indices where snippets[i].collection == name { snippets[i].collection = "" }
        changed()
    }

    func snippets(in collection: String?, matching q: String = "") -> [Snippet] {
        snippets.filter { collection == nil || $0.collection == collection }
            .filter { q.isEmpty || $0.title.localizedCaseInsensitiveContains(q) || $0.text.localizedCaseInsensitiveContains(q) }
    }

    /// Turns a history item into a snippet.
    func saveAsSnippet(_ item: ClipItem) -> Snippet? {
        guard item.kind == .text || item.kind == .link else { return nil }
        return addSnippet(title: item.title, text: item.text)
    }
}

/// Paste straight into the front app (⌘V), which needs Accessibility permission.
@MainActor
enum Paster {
    static var trusted: Bool { AXIsProcessTrusted() }

    /// Shows the macOS Accessibility prompt (only called from the settings toggle).
    static func askForPermission() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    static func pasteToFrontApp() {
        guard trusted else { return }
        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)   // V
        let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
